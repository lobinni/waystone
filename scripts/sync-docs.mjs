// scripts/sync-docs.mjs
// Regenerates src/docs/content.ts from the markdown files in src/docs.
// The website never imports .md directly; it imports this generated module.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/docs/", import.meta.url);
const out = new URL("../src/docs/content.ts", import.meta.url);

const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
const bodies = files.map((f) => [f.replace(/\.md$/, ""), readFileSync(new URL(f, dir), "utf8")]);

const body = bodies
  .map(([slug, md]) => `  ${JSON.stringify(slug)}:\n    ${JSON.stringify(md)},`)
  .join("\n");

writeFileSync(
  out,
  "// Generated by scripts/sync-docs.mjs from the markdown files next to this module.\n" +
    "// Edit the .md files and run the script again; never edit this file by hand.\n\n" +
    "export const DOC_BODIES: Record<string, string> = {\n" +
    body +
    "\n};\n",
);

console.log(`Wrote src/docs/content.ts from ${bodies.length} pages.`);
